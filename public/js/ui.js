export function icon(name, cls = '') {
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${P[name] || ''}</svg>`;
}

export function debounce(fn, ms) {
  let t;
  const d = (...args) => {
    clearTimeout(t);
    t = setTimeout(() => fn(...args), ms);
  };
  d.flush = (...args) => {
    clearTimeout(t);
    fn(...args);
  };
  return d;
}

export function toast(message, kind = 'info', ms = 3200) {
  let host = document.getElementById('toasts');
  if (!host) {
    host = document.createElement('div');
    host.id = 'toasts';
    host.setAttribute('role', 'status');
    host.setAttribute('aria-live', 'polite');
    document.body.appendChild(host);
  }
  const el = document.createElement('div');
  el.className = `toast toast-${kind}`;
  el.innerHTML = `${icon(kind === 'error' ? 'alert' : kind === 'success' ? 'check' : 'info')}<span>${esc(message)}</span>`;
  host.appendChild(el);
  requestAnimationFrame(() => el.classList.add('in'));
  setTimeout(() => {
    el.classList.remove('in');
    setTimeout(() => el.remove(), 300);
  }, ms);
}

// Promise-based modal. `body` is HTML; buttons: [{label, value, kind}]
export function modal({ title, body, buttons = [{ label: t('OK'), value: true, kind: 'primary' }], wide = false, onMount }) {
  return new Promise((resolve) => {
    const wrap = document.createElement('div');
    wrap.className = 'modal-backdrop';
    wrap.innerHTML = `<div class="modal ${wide ? 'wide' : ''}" role="dialog" aria-modal="true" aria-label="${attr(title)}">
      <header><h2>${esc(title)}</h2><button class="icon-btn" data-close aria-label="${attr(t('Close'))}">${icon('x')}</button></header>
      <div class="modal-body">${body}</div>
      <footer>${buttons.map((b, i) => `<button class="btn ${b.kind || ''}" data-btn="${i}">${esc(b.label)}</button>`).join('')}</footer>
    </div>`;
    const close = (value) => {
      wrap.remove();
      document.removeEventListener('keydown', onKey);
      resolve(value);
    };
    const onKey = (e) => {
      if (e.key === 'Escape') close(undefined);
    };
    wrap.addEventListener('click', (e) => {
      if (e.target === wrap || e.target.closest('[data-close]')) close(undefined);
      const b = e.target.closest('[data-btn]');
      if (b) {
        const spec = buttons[Number(b.dataset.btn)];
        close(typeof spec.value === 'function' ? spec.value(wrap) : spec.value);
      }
    });
    document.addEventListener('keydown', onKey);
    document.body.appendChild(wrap);
    onMount?.(wrap);
    (wrap.querySelector('input,textarea,select') || wrap.querySelector('[data-btn]'))?.focus();
  });
}

export async function confirmDialog(title, message, okLabel = t('Delete')) {
  return modal({
    title,
    body: `<p>${esc(message)}</p>`,
    buttons: [{ label: t('Cancel'), value: false }, { label: okLabel, value: true, kind: 'danger' }],
  });
}

export async function promptDialog(title, label, value = '') {
  return modal({
    title,
    body: `<label class="field"><span class="lbl">${esc(label)}</span><input class="inp" id="prompt-input" value="${attr(value)}"></label>`,
    buttons: [{ label: t('Cancel'), value: null }, { label: t('OK'), value: (w) => w.querySelector('#prompt-input').value, kind: 'primary' }],
    onMount: (w) => {
      const inp = w.querySelector('#prompt-input');
      inp.addEventListener('keydown', (e) => {
        if (e.key === 'Enter') w.querySelector('[data-btn="1"]').click();
      });
    },
  });
}

export function download(filename, text, type = 'application/json') {
  const blob = new Blob([text], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

// Minimal, safe markdown for chat replies: escape first, then format.
export function mdLite(src) {
  const lines = esc(src).split('\n');
  const out = [];
  let list = null;
  const inline = (s) => s
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
    .replace(/(^|\s)_([^_]+)_(?=\s|$|[.,;:!?])/g, '$1<em>$2</em>');
  const closeList = () => {
    if (list) out.push(`</${list}>`);
    list = null;
  };
  for (const raw of lines) {
    const line = raw.trimEnd();
    const ul = line.match(/^\s*[-*•]\s+(.*)/);
    const ol = line.match(/^\s*\d+[.)]\s+(.*)/);
    const h = line.match(/^#{1,4}\s+(.*)/);
    if (ul || ol) {
      const kind = ul ? 'ul' : 'ol';
      if (list !== kind) {
        closeList();
        out.push(`<${kind}>`);
        list = kind;
      }
      out.push(`<li>${inline((ul || ol)[1])}</li>`);
      continue;
    }
    closeList();
    if (h) out.push(`<h4>${inline(h[1])}</h4>`);
    else if (/^&gt;\s?/.test(line)) out.push(`<blockquote>${inline(line.replace(/^&gt;\s?/, ''))}</blockquote>`);
    else if (line.trim()) out.push(`<p>${inline(line)}</p>`);
  }
  closeList();
  return out.join('');
}

export function initials(name) {
  const parts = String(name || '?').trim().split(/\s+/).filter(Boolean);
  return ((parts[0]?.[0] || '?') + (parts.length > 1 ? parts[parts.length - 1][0] : '')).toUpperCase();
}

export function timeAgo(iso) {
  if (!iso) return '';
  const s = (Date.now() - new Date(iso).getTime()) / 1000;
  if (s < 60) return t('just now');
  if (s < 3600) return t('{n} min ago', { n: Math.floor(s / 60) });
  if (s < 86400) return t('{n} h ago', { n: Math.floor(s / 3600) });
  return new Date(iso).toLocaleDateString(getLocale());
}

export function autoGrow(el) {
  el.style.height = 'auto';
  el.style.height = `${Math.min(el.scrollHeight + 2, 600)}px`;
}
